import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const load = async (p) => JSON.parse(await fs.readFile(path.join(root, p), 'utf8'));
const master = await load('content/english/master/module-content-and-mechanics-v1.json');
const registry = await load('content/mechanics/canonical-mechanics-registry.json');
const canonical = new Set(Object.values(registry.mechanics).filter((m) => m.status === 'PRODUCTION_CANONICAL_LOCKED').map((m) => m.mechanicId));
const allowed = new Set(['target-shooter','bubble-pop','drag-drop-multimedia','drag-drop','matching','memory-quest','smart-sentence-complete','smart-sentence-order']);
const blocked = new Set(['smart-sentence-unscramble']);
const modes = new Set(['AUDIO_IMAGE','TEXT_IMAGE','AUDIO_TEXT']);
const requiredFields = ['moduleId','activityId','sequencePosition','topicEn','pedagogicalPhase','learningTarget','contentFamily','languageTargets','vocabularyStatus','mechanicId','primaryInstructionEn','supportInstructionPt','stimulusType','expectedStudentAction','expectedResponseType','answerContract','audioRequirements','imageRequirements','mediaRequirements','whyThisMechanic','priorKnowledge','spiralReference','duplicateRisk','productionStatus','productionNotes'];
const errors = [];
const ids = master.modules.map((m) => m.moduleId);
let total = 0;
let mqTotal = 0;
const mechanicTotals = Object.fromEntries([...allowed].map((x) => [x,0]));
const mqByMode = { AUDIO_IMAGE:0, TEXT_IMAGE:0, AUDIO_TEXT:0 };
const mqByYear = { Y1:0,Y2:0,Y3:0,Y4:0,Y5:0 };
const mqCounts = [];
const nearDuplicates = master.duplicationReview ?? [];
const exactMq = new Set();
let imageMapped = 0;
let audioMapped = 0;
let maxStreak = 0;
const monotony = [];
const contentSignatures = new Set();
const skinSignatures = new Map();
if (master.modules.length !== 30) errors.push(`Expected 30 modules; got ${master.modules.length}`);
if (new Set(ids).size !== 30) errors.push('Module IDs are not unique');
if (master.activityCountStandard?.perModule !== 20 || master.activityCountStandard?.totalActivities !== 600) errors.push('Missing authoritative 20 × 30 activity standard');
for (const m of master.modules) {
  const list = m.activitySequence ?? [];
  const expectedIds = Array.from({length:20},(_,i)=>`Q${String(i+1).padStart(3,'0')}`);
  if (m.activityCount?.value !== 20 || list.length !== 20) errors.push(`${m.moduleId}: expected exactly 20 activities`);
  if (JSON.stringify(list.map((a)=>a.activityId)) !== JSON.stringify(expectedIds)) errors.push(`${m.moduleId}: activity IDs/sequence must be Q001–Q020 exactly`);
  const mq = list.filter((a)=>a.mechanicId === 'memory-quest');
  mqCounts.push({moduleId:m.moduleId,count:mq.length,positions:mq.map((a)=>a.activityId)});
  if (mq.length < 2) errors.push(`${m.moduleId}: MQ_MINIMUM_DISTRIBUTION_NOT_MET`);
  if (m.memoryQuestPlan?.confirmedCount !== mq.length) errors.push(`${m.moduleId}: MQ summary count mismatch`);
  let previousWasMq = false;
  const seenMq = new Set();
  let run = 0, moduleMaxStreak = 0, previous = null;
  for (const a of list) {
    total++;
    if (!allowed.has(a.mechanicId) || !canonical.has(a.mechanicId)) errors.push(`${m.moduleId}/${a.activityId}: mechanic is not an allowed locked activity mechanic (${a.mechanicId})`);
    if (blocked.has(a.mechanicId)) errors.push(`${m.moduleId}/${a.activityId}: blocked mechanic used`);
    if (a.mechanicId in mechanicTotals) mechanicTotals[a.mechanicId]++;
    for (const f of requiredFields) if (a[f] === undefined || a[f] === null || a[f] === '') errors.push(`${m.moduleId}/${a.activityId}: missing ${f}`);
    const semanticSet = (a.languageTargets ?? []).map((x)=>String(x).trim().toLowerCase()).sort().join('|');
    const demand = `${a.pedagogicalPhase}|${a.stimulusType}|${a.expectedStudentAction}`;
    const exact = `${m.moduleId}|${semanticSet}|${demand}|${a.mechanicMode ?? ''}|${a.mechanicId}`;
    if (contentSignatures.has(exact)) errors.push(`${m.moduleId}/${a.activityId}: EXACT_CONTENT_DUPLICATE`);
    contentSignatures.add(exact);
    const skin = `${m.moduleId}|${semanticSet}|${demand}|${a.mechanicMode ?? ''}`;
    const priorMechanic = skinSignatures.get(skin);
    if (priorMechanic && priorMechanic.mechanicId !== a.mechanicId) errors.push(`${m.moduleId}/${a.activityId}: MECHANIC_SKIN_DUPLICATE with ${priorMechanic.activityId}`);
    else if (!priorMechanic) skinSignatures.set(skin,{activityId:a.activityId,mechanicId:a.mechanicId});
    if (a.audioRequirements?.instructionAudioRequired) audioMapped++;
    if (Array.isArray(a.imageRequirements) && a.imageRequirements.length) imageMapped++;
    if (a.mechanicId === 'memory-quest') {
      mqTotal++;
      if (!modes.has(a.mechanicMode)) errors.push(`${m.moduleId}/${a.activityId}: invalid MQ mode`);
      if (previousWasMq) errors.push(`${m.moduleId}/${a.activityId}: MQ_CONSECUTIVE_USAGE`);
      previousWasMq = true;
      const ac = a.answerContract ?? {};
      if (!Number.isInteger(ac.pairCount) || ac.pairCount < 2 || ac.pairCount > 6) errors.push(`${m.moduleId}/${a.activityId}: MQ pair count outside supported planning range (2–6)`);
      if (!Array.isArray(ac.targetSet) || ac.targetSet.length !== ac.pairCount) errors.push(`${m.moduleId}/${a.activityId}: MQ target set/pair count mismatch`);
      const sig = `${a.mechanicMode}|${[...(ac.targetSet??[])].sort().join('|')}`;
      if (seenMq.has(sig)) errors.push(`${m.moduleId}: MQ_EXACT_DUPLICATE`);
      seenMq.add(sig);
      mqByMode[a.mechanicMode]++;
      mqByYear[`Y${m.year}`]++;
    } else previousWasMq = false;
    if (a.mechanicId === previous) run++;
    else { previous = a.mechanicId; run = 1; }
    moduleMaxStreak = Math.max(moduleMaxStreak,run);
    maxStreak = Math.max(maxStreak,run);
  }
  if (m.memoryQuestPlan?.positions?.some((id,i,a)=>i>0 && (Number(id.slice(1))-Number(a[i-1].slice(1))===1))) errors.push(`${m.moduleId}: summary has consecutive MQ positions`);
  if (moduleMaxStreak >= 4) monotony.push(`${m.moduleId}: streak ${moduleMaxStreak}; check differentiated task purpose before production`);
  if (m.longestSameMechanicStreak !== moduleMaxStreak) errors.push(`${m.moduleId}: recorded longest mechanic streak does not match sequence`);
}
if (total !== 600) errors.push(`Expected 600 activity records; got ${total}`);
if (mqTotal < 60) errors.push(`Expected at least 60 MQ activities; got ${mqTotal}`);
if (Object.values(mqCounts).filter((x)=>x.count>=2).length !== 30) errors.push('Not all modules meet the MQ minimum');
if (nearDuplicates.some((x)=>!x.rationale && !x.reason)) errors.push('Near-duplicate review entry lacks rationale');
if (master.lowFitResolutions && !['Y1M05','Y3M05','Y5M04'].every((id)=>(master.lowFitResolutions[id]??[]).length>=2)) errors.push('A historical LOW-fit module lacks two explicit supported MQ uses');
console.log(`MODULES: ${new Set(ids).size}/30`);
console.log(`ACTIVITY RECORDS: ${total}/600`);
console.log(`MODULES WITH 20 ACTIVITIES: ${master.modules.filter((m)=>m.activitySequence?.length===20).length}/30`);
console.log(`MODULES WITH >=2 MEMORY QUEST: ${mqCounts.filter((x)=>x.count>=2).length}/30`);
console.log(`TOTAL MEMORY QUEST: ${mqTotal}`);
console.log(`MQ MODES: ${JSON.stringify(mqByMode)}`);
console.log(`MQ BY YEAR: ${JSON.stringify(mqByYear)}`);
console.log(`MECHANIC TOTALS: ${JSON.stringify({...mechanicTotals, 'drag-drop-grouping': mechanicTotals['drag-drop']})}`);
console.log(`BLOCKED MECHANICS: ${total - Object.values(mechanicTotals).reduce((a,b)=>a+b,0)}`);
console.log(`AUDIO INSTRUCTION REQUIREMENTS: ${audioMapped}/600`);
console.log(`IMAGE-DEPENDENT ACTIVITIES WITH IMAGE SLOTS: ${imageMapped}`);
console.log(`NEAR-DUPLICATE REVIEW ITEMS: ${nearDuplicates.length}`);
console.log(`EXACT CONTENT DUPLICATE SIGNATURES: ${errors.filter((x)=>x.includes('EXACT_CONTENT_DUPLICATE')).length}`);
console.log(`MECHANIC SKIN DUPLICATE SIGNATURES: ${errors.filter((x)=>x.includes('MECHANIC_SKIN_DUPLICATE')).length}`);
console.log(`LONGEST RECORDED SAME-MECHANIC STREAK: ${maxStreak}; monotony flags ${monotony.length}`);
if (errors.length) {
  console.error(`PLANNING VALIDATION: ISSUE (${errors.length})`);
  for (const e of errors.slice(0,80)) console.error(`- ${e}`);
  process.exitCode = 1;
} else console.log('PLANNING VALIDATION: PASS');
