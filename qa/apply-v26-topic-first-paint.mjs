import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
const hash=data=>createHash('sha256').update(data).digest('hex');
const path='dist-pages/.duduq-pages-manifest';
const original=readFileSync(path);
if(!original.equals(readFileSync('qa/results/v25-early-header-manifest.txt'))) throw Error('V26_FROZEN_V25_MANIFEST_MISMATCH');
const lines=original.toString('utf8').trimEnd().split(/\r?\n/);
if(lines.length!==2673)throw Error('V26_MANIFEST_COUNT_INVALID:'+lines.length);
const files=new Map();
for(let i=0;i<lines.length;i++){
 const at=lines[i].lastIndexOf(' '),name=lines[i].slice(0,at),sha=lines[i].slice(at+1);
 if(at<1||files.has(name)||!/^[a-f0-9]{64}$/.test(sha))throw Error('V26_BAD_MANIFEST:'+name);
 files.set(name,{sha,index:i});
}
const cssString=s=>String(s).replace(/\\/g,'\\\\').replace(/"/g,'\\"').replace(/</g,'\\3c ').replace(/\r/g,' ').replace(/\n/g,' ');
const topics=new Map();
for(let y=1;y<=5;y++)for(let m=1;m<=6;m++){
 const mm=String(m).padStart(2,'0');
 const data=JSON.parse(readFileSync('dist-pages/content/english/year-'+y+'/module-'+mm+'/questions.json','utf8'));
 if(data.items?.length!==20)throw Error('V26_EXPECTED_20_QUESTIONS:Y'+y+'M'+mm);
 for(const item of data.items){
   const full=String(item.topicEn||'').replace(/\s+/g,' ').trim();
   if(full.length<=28)continue;
   const colon=full.indexOf(':');
   const prefix=colon>0?full.slice(0,colon).trim():'';
   if(prefix.length<8||prefix.length>25)continue;
   if(prefix===full||/</.test(full))throw Error('V26_INVALID_TOPIC:'+full);
   topics.set(full,prefix);
 }
}
const required='Choices Around Me: Food, School and Preferences';
if(topics.get(required)!=='Choices Around Me')throw Error('V26_TARGET_Y3M06_MISSING');
const rules=['/* V26 critical CSS: topic titles fit before JS or browser first paint. Generated from approved curriculum. */'];
for(const [full,short] of [...topics].sort((a,b)=>a[0].localeCompare(b[0]))){
 const selector='#game .duduq-canonical-header-hud .hud-title[data-topic-en="'+cssString(full)+'"]';
 const size=short.length<=16?20:short.length<=21?18:16;
 rules.push(selector+'{position:absolute!important;top:0!important;transform:none!important;display:block!important;width:160px!important;max-width:160px!important;height:56px!important;min-height:56px!important;max-height:56px!important;overflow:hidden!important;white-space:normal!important;font-size:0!important;color:transparent!important;}');
 rules.push(selector+'::before{content:"'+cssString(short)+'"!important;position:absolute!important;inset:0!important;box-sizing:border-box!important;display:flex!important;align-items:center!important;justify-content:flex-start!important;width:160px!important;height:56px!important;overflow:hidden!important;color:#364b43!important;font-family:"Nunito",sans-serif!important;font-weight:900!important;font-size:'+size+'px!important;line-height:1.12!important;letter-spacing:0!important;text-align:left!important;white-space:normal!important;text-wrap:balance!important;}');
}
const early='<script src="/core/duduq-header-title-fit-v24.js" data-duduq-header-title-fit="v24"></script>';
const style='<style id="duduq-v26-topic-first-paint">\n'+rules.join('\n')+'\n</style>';
const targets=[...files.keys()].filter(p=>p==='index.html'||p==='home/index.html'||(p.startsWith('play/')&&p.endsWith('/index.html')));
if(targets.length!==43)throw Error('V26_ROUTES_INVALID:'+targets.length);
for(const name of targets){
 const bytes=readFileSync('dist-pages/'+name);
 if(hash(bytes)!==files.get(name).sha)throw Error('V26_UNEXPECTED_HTML:'+name);
 let html=bytes.toString('utf8');
 if(html.split(early).length!==2)throw Error('V26_EARLY_SCRIPT_REQUIRED:'+name);
 if(html.includes('duduq-v26-topic-first-paint'))throw Error('V26_DUPLICATED_STYLE:'+name);
 html=html.replace(early,style+'\n    '+early);
 writeFileSync('dist-pages/'+name,html);
 lines[files.get(name).index]=name+' '+hash(Buffer.from(html));
}
const output=Buffer.from(lines.join('\n')+'\n');
writeFileSync(path,output);
mkdirSync('qa/results',{recursive:true});
writeFileSync('qa/results/v26-title-first-paint-manifest.txt',output);
console.log('V26_CURRICULUM_TITLES_AUTOGENERATED=PASS:'+topics.size);
console.log('V26_Y3M06_CRITICAL_TOPIC=PASS');
console.log('V26_CRITICAL_CSS_43_ROUTES=PASS');
console.log('V26_GOLD_MASTERS_UNCHANGED=PASS');
console.log('V26_MANIFEST=PASS:'+hash(output).toUpperCase()+':2673');
